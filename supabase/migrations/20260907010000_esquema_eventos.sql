create index idx_comissao_evento on eventos.comissao_membros (evento_id);

-- ── Régua de e-mail por evento ─────────────────────────────────────────────
--
-- ⚠️ Isto é a REGRA, não a mensagem. O envio continua passando por
-- `public.notificacoes` — a fila é uma só (regra do AGENTS.md), e um módulo
-- com fila própria significaria duas coisas para monitorar, dois lugares onde
-- uma mensagem pode ficar presa, e nenhuma visão de conjunto.
create table eventos.reguas_email (
  id            integer primary key generated by default as identity,
  legado_id     integer unique,
  evento_id     integer not null references eventos.eventos(id) on delete cascade,
  nome_interno  text not null,
  assunto       text not null,
  corpo         text,
  -- 'data' dispara num instante; 'relativo' N dias antes ou depois do evento.
  agendamento   text not null default 'data' check (agendamento in ('data','relativo')),
  data_envio    timestamptz,
  dias          smallint,
  -- A quem: todos, quem comprou certo tipo, quem fez check-in, quem não fez.
  segmento      text not null default 'todos',
  ingresso_tipo_id integer references eventos.ingresso_tipos(id) on delete cascade,
  anexar_voucher boolean not null default false,
  ativo         boolean not null default true,
  criado_em     timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint agendamento_coerente check (
    (agendamento = 'data'     and data_envio is not null) or
    (agendamento = 'relativo' and dias is not null)
  )
);

-- Quem recebe aviso quando alguém compra. Era `RegionalPromotorEmail`.
create table eventos.avisos_compra (
