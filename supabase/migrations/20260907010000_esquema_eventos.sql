-- ── RLS ligada, GRANT nenhum ───────────────────────────────────────────────
--
-- O navegador NUNCA fala com estas tabelas: quem fala é o servidor, pelo
-- pooler, e a autorização acontece por capacidade antes de qualquer consulta
-- (decisão 0003). RLS ligada mesmo assim, porque `anon` e `authenticated` não
-- podem alcançar nada nem por engano — e porque uma tabela sem RLS que ganhe
-- GRANT no futuro ficaria aberta em silêncio.
do $$
declare t text;
begin
  for t in select tablename from pg_tables where schemaname = 'eventos' loop
    execute format('alter table eventos.%I enable row level security', t);
    execute format('revoke all on eventos.%I from anon, authenticated', t);
  end loop;
end $$;

revoke usage on schema eventos from anon, authenticated;

comment on schema eventos is
  'Módulo de eventos. Acesso só pelo servidor, via Postgres direto (decisão 0003). Sem GRANT para anon/authenticated.';
